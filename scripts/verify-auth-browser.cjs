// Runs backend + Vite + Chrome against a disposable local MongoDB. No real SMTP or data.
process.env.NODE_ENV = 'test';
process.env.MONGO_URI = 'mongodb://127.0.0.1:27017/unused';
process.env.API_KEY = 'browser-test-api-key';
delete process.env.VITE_API_KEY;
process.env.JWT_SECRET = 'browser-test-only-secret-of-more-than-32-bytes';
process.env.AUTH_2FA_ENCRYPTION_KEY = '43'.repeat(32);
process.env.FRONTEND_URL = 'http://127.0.0.1';
process.env.LOG_LEVEL = 'silent';
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const net = require('node:net');
const { pathToFileURL } = require('node:url');
const { spawn } = require('node:child_process');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');
const { chromium } = require('playwright-core');
const mailer = require('../src/services/mailer');
const mails = [];
mailer.sendMail = (to, subject, text) => mails.push({ to, subject, text });
const { app } = require('../src/server');
const Staff = require('../src/models/Staff');
const Customer = require('../src/models/Customer');
let browser, vite, api, mongo, dir;
async function main() {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'license-auth-browser-'));
  const probe = net.createServer();
  await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const mongoPort = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  mongo = spawn('mongod', ['--dbpath', dir, '--port', String(mongoPort), '--bind_ip', '127.0.0.1', '--nounixsocket', '--quiet'], { stdio: 'ignore' });
  let started = false;
  for (let i = 0; i < 20; i++) {
    try { await mongoose.connect(`mongodb://127.0.0.1:${mongoPort}/auth_browser_test`, { serverSelectionTimeoutMS: 500 }); started = true; break; } catch { /* startup */ }
  }
  assert.ok(started, 'MongoDB started');
  const password = 'BrowserPass123';
  const hashed = await bcrypt.hash(password, 12);
  await Promise.all([Staff.init(), Customer.init()]);
  await Staff.create({ email: 'staff@example.com', password: hashed, role: 'admin', twoFactorEnabled: true });
  await Customer.create({ email: 'customer@example.com', password: hashed });
  api = await new Promise(resolve => { const server = app.listen(0, '127.0.0.1', () => resolve(server)); });
  const { createServer } = await import(pathToFileURL(path.resolve(__dirname, '../frontend/node_modules/vite/dist/node/index.js')));
  vite = await createServer({ root: path.resolve(__dirname, '../frontend'), configFile: path.resolve(__dirname, '../frontend/vite.config.js'),
    server: { host: '127.0.0.1', port: 0, proxy: { '/api': { target: `http://127.0.0.1:${api.address().port}`, changeOrigin: true } } } });
  await vite.listen();
  const base = `http://127.0.0.1:${vite.httpServer.address().port}`;
  process.env.FRONTEND_URL = base;
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  for (const path of ['/', '/admin/', '/admin/licenses', '/admin/licenses/new', '/licenses']) {
    await page.goto(`${base}${path}`);
    await page.waitForURL('**/admin/authentication');
    assert.equal(await page.getByRole('heading', { name: 'Licenses', exact: true }).count(), 0);
  }
  await page.goto(`${base}/portal`);
  await page.waitForURL('**/authentication/login');
  await page.getByRole('heading', { name: 'Please login', exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/license-customer-login-desktop.png', fullPage: true });
  await page.getByLabel('Language').selectOption('en');
  await page.getByRole('button', { name: 'Knowledge Base' }).click();
  await page.getByRole('heading', { name: 'Login help' }).waitFor();
  await page.getByRole('button', { name: 'Close knowledge base' }).click();
  await page.getByLabel('Email Address', { exact: true }).fill('customer@example.com');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  assert.equal(await page.locator('#password').getAttribute('type'), 'text');
  await page.getByLabel('Remember me', { exact: true }).check();
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/portal');
  await page.getByText('Signed in as customer@example.com').waitFor();
  await page.goto(`${base}/admin/licenses`); await page.waitForURL('**/portal');
  const denied = await context.request.get(`${base}/api/licenses`);
  assert.equal(denied.status(), 403);
  const before = (await context.cookies()).find(c => c.name === 'remember_token').value;
  await context.clearCookies({ name: 'auth_access' });
  await page.reload();
  await page.getByText('Signed in as customer@example.com').waitFor();
  assert.notEqual((await context.cookies()).find(c => c.name === 'remember_token').value, before);
  assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(k => /token/i.test(k)).length), 0);
  await page.getByRole('button', { name: 'Open account menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'My Profile', exact: true }).click();
  await page.getByRole('dialog').getByText('customer@example.com', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close profile' }).click();
  await page.getByRole('button', { name: 'Open account menu', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('menu', { name: 'Profile', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Open account menu', exact: true }).click();
  await page.route('**/api/auth/logout', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Please retry logout' }) }));
  await page.getByRole('menuitem', { name: 'Logout', exact: true }).click();
  await page.locator('.profile-menu-error').getByText('Please retry logout').waitFor();
  assert.equal(new URL(page.url()).pathname, '/portal');
  await page.unroute('**/api/auth/logout');
  await page.getByRole('menuitem', { name: 'Logout', exact: true }).click();
  await page.waitForURL('**/authentication/login');
  assert.equal((await context.cookies()).some(c => ['auth_access', 'remember_token'].includes(c.name)), false);
  await page.goto(`${base}/portal`); await page.waitForURL('**/authentication/login');
  console.log('PASS customer login/refresh, profile dialog, keyboard dismissal, failed logout retry, successful logout, cleared cookies and protected route denial');
  await page.goto(`${base}/admin/login`);
  await page.waitForURL('**/admin/authentication');
  await page.screenshot({ path: '/tmp/license-admin-login-desktop.png', fullPage: true });
  await page.getByLabel('Email Address', { exact: true }).fill('staff@example.com');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/verify-2fa');
  assert.equal(new URL(page.url()).search, '');
  const code = mails.at(-1).text.match(/code is (\d{6})/)[1];
  await page.getByLabel('Verification code').fill(code);
  await page.getByRole('button', { name: 'Verify', exact: true }).click();
  await page.waitForURL('**/admin/');
  await page.getByText('Signed in as staff@example.com').waitFor();
  await page.goto(`${base}/portal`); await page.waitForURL('**/admin/');
  await page.getByRole('link', { name: 'Client License', exact: true }).click();
  await page.waitForURL('**/admin/licenses');
  await page.getByRole('heading', { name: 'Licenses', exact: true }).waitFor();
  const protectedData = await context.request.get(`${base}/api/licenses`);
  assert.equal(protectedData.status(), 200);
  await page.getByRole('link', { name: '+ New License', exact: true }).click();
  await page.waitForURL('**/admin/licenses/new');
  await page.locator('#product-name').waitFor();
  await page.goto(`${base}/licenses`); await page.waitForURL('**/admin/licenses');
  await page.locator('.sidebar .user-email').getByText('staff@example.com', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open profile menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Language', exact: true }).click();
  await page.getByText('English ✓', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Open profile menu', exact: true }).click();
  await page.screenshot({ path: '/tmp/license-profile-logout.png', fullPage: true });
  await page.getByRole('menuitem', { name: 'Logout', exact: true }).click();
  await page.waitForURL('**/admin/authentication');
  assert.equal((await context.cookies()).some(c => ['auth_access', 'remember_token'].includes(c.name)), false);
  await page.goto(`${base}/admin`); await page.waitForURL('**/admin/authentication');
  console.log('PASS staff login, in-memory 2FA, profile dropdown on license sidebar, language, logout, cleared cookies, protected route denial');
  await page.goto(`${base}/forgot-password?type=customer`);
  await page.getByLabel('Email', { exact: true }).fill('customer@example.com');
  await page.getByRole('button', { name: 'Send reset link' }).click();
  await page.getByText('If the email exists, a reset link has been sent').waitFor();
  const resetLink = mails.at(-1).text.match(/https?:\/\/\S+/)[0];
  await page.goto(resetLink);
  await page.getByLabel('Password', { exact: true }).fill('weak');
  await page.getByLabel('Confirm password', { exact: true }).fill('weak');
  await page.getByRole('button', { name: 'Reset password' }).click();
  await page.getByRole('alert').filter({ hasText: 'At least 8 characters' }).waitFor();
  await page.getByLabel('Password', { exact: true }).fill('ChangedPass123');
  await page.getByLabel('Confirm password', { exact: true }).fill('ChangedPass123');
  await page.getByRole('button', { name: 'Reset password' }).click(); await page.waitForURL('**/authentication/login');
  console.log('PASS forgot/reset flow, inline strength validation, login redirect');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/license-auth-mobile.png', fullPage: true });
  await page.goto(`${base}/admin/authentication`);
  await page.screenshot({ path: '/tmp/license-admin-login-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.goto(`${base}/admin/licenses`); await page.waitForURL('**/admin/authentication');
  assert.equal(await page.getByRole('heading', { name: 'Licenses', exact: true }).count(), 0);
  const afterLogout = await context.request.get(`${base}/api/licenses`);
  assert.equal(afterLogout.status(), 401);
  console.log('PASS admin route protection, dashboard-to-license navigation, create form, legacy redirect, customer/API-key rejection and mobile layout');
  assert.deepEqual(errors, []);
  console.log('PASS no browser JavaScript errors');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await browser?.close(); await vite?.close();
  if (api) await new Promise(resolve => api.close(resolve));
  await mongoose.disconnect();
  if (mongo && mongo.exitCode === null) { const exited = new Promise(resolve => mongo.once('exit', resolve)); mongo.kill('SIGTERM'); await exited; }
  if (dir) fs.rmSync(dir, { recursive: true, force: true });
});
